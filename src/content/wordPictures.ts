/**
 * Which recorded words can be shown as a picture (for silent exercises:
 * a picture prompt in place of the word's audio).
 *
 * A first-pass judgement, not settled content: browse and revise it at
 * /dbg/word-pictures. Words absent here are `no` (function words,
 * abstractions, names).
 *
 * The main risk isn't drawability but naming: will a child call the picture
 * by the word it spells? `rivals` lists the common other names. Missing-letter
 * and multiple-choice exercises survive a rival (m_g can't be "cup"; keep
 * rivals out of the options); flat spelling doesn't.
 */

export type PictureVerdict = "drawable" | "iffy" | "no";

/** Why an iffy word is iffy. */
export type IffyKind =
  /** One clear icon, but faces are the LetterPeople's own medium. */
  | "emotion"
  /** A still image of an action reads as its noun (kick → "ball"). */
  | "action"
  /** Arrows, ticks and crosses: drawable, but they collide with UI meanings. */
  | "symbol"
  /** Needs a pair or a scene (big, tall, mom). */
  | "relational"
  /** The picture has its own, different name (buzz → "bee"). */
  | "stand-in"
  /** A noun worth trying; the picture may or may not read. */
  | "borderline";

export interface WordPicture {
  verdict: Exclude<PictureVerdict, "no">;
  /** For iffy words. */
  kind?: IffyKind;
  /** Stand-in until there's real art. */
  emoji?: string;
  /** Other names a child might give the picture. */
  rivals?: string[];
  note?: string;
  /**
   * The recording and the picture may disagree on pronunciation (heteronyms):
   * check the clip by ear before using the picture.
   */
  checkAudio?: string;
}

const d = (emoji?: string, extra: Partial<WordPicture> = {}): WordPicture => ({ verdict: "drawable", emoji, ...extra });
const i = (kind: IffyKind, emoji?: string, extra: Partial<WordPicture> = {}): WordPicture => ({
  verdict: "iffy",
  kind,
  emoji,
  ...extra,
});

