/** The catalog entry, or undefined for a `no` word. */
export function wordPicture(word: string): WordPicture | undefined {
  return WORD_PICTURES[word];
}

export function pictureVerdict(word: string): PictureVerdict {
  return WORD_PICTURES[word]?.verdict ?? "no";
}
